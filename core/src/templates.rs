//! Библиотека готовых шаблонов перфорации. Шаблон меняет только настройки узора,
//! сохраняя размеры листа, картинку, металл, цены и язык.

use crate::params::Params;

#[derive(Clone, Debug)]
pub struct Template {
    pub id: &'static str,
    pub name: &'static str,
    pub desc: &'static str,
    /// Тип мини-превью: square | tri | hex | radial | mosaic | rhomb | stipple | rings | lines
    pub preview: &'static str,
    pub pattern: &'static str,
    pub grid: &'static str,
    pub shape: &'static str,
    pub size_mode: &'static str,
    pub pitch: f64,
    pub d_min: f64,
    pub d_max: f64,
    pub bridge: f64,
    pub angle: f64,
    pub tone_cut: f64,
    pub wave: bool,
    pub star_points: u32,
    pub mjoint_n: i64,
    pub line_pitch: f64,
}

const fn t(
    id: &'static str,
    name: &'static str,
    desc: &'static str,
    preview: &'static str,
    pattern: &'static str,
    grid: &'static str,
    shape: &'static str,
    size_mode: &'static str,
    pitch: f64,
    d_min: f64,
    d_max: f64,
    bridge: f64,
    angle: f64,
    tone_cut: f64,
    wave: bool,
    star_points: u32,
    mjoint_n: i64,
    line_pitch: f64,
) -> Template {
    Template {
        id,
        name,
        desc,
        preview,
        pattern,
        grid,
        shape,
        size_mode,
        pitch,
        d_min,
        d_max,
        bridge,
        angle,
        tone_cut,
        wave,
        star_points,
        mjoint_n,
        line_pitch,
    }
}

