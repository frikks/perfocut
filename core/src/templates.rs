impl Template {
    /// Категория по id — не меняет статические данные шаблонов.
    pub fn category(&self) -> &'static str {
        match self.id {
            "speaker" | "micro" | "large" => "dynamic",
            "vent" | "louver" | "galvanized" => "vent",
            "radial" | "mosaic" | "rhomb" | "sine" | "rings" | "stipple" | "star" => "decor",
            _ => "structure",
        }
    }

    /// Применяет шаблон, сохраняя лист, картинку, металл, цены и язык.
    pub fn apply_to(&self, base: &Params) -> Params {
        let mut p = base.clone();
        p.pattern = self.pattern.into();
        p.grid = self.grid.into();
        p.shape = self.shape.into();
        p.size_mode = self.size_mode.into();
        p.pitch = self.pitch;
        p.d_min = self.d_min;
        p.d_max = self.d_max;
        p.bridge = self.bridge;
        p.angle = self.angle;
        p.tone_cut = self.tone_cut;
        p.wave = self.wave;
        p.star_points = self.star_points;
        p.mjoint_n = self.mjoint_n;
        p.line_pitch = self.line_pitch;
        // Сбрасываем то, что может испортить выбранный узор
        p.grid_aspect = 1.0;
        p.fixed = false;
        p.jitter = 0.0;
        p.wave_len = 80.0;
        p.wave_amp = 6.0;
        p.offset_x = 0.0;
        p.offset_y = 0.0;
        p
    }
}

pub fn find(id: &str) -> Option<&'static Template> {
    TEMPLATES.iter().find(|t| t.id == id)
}
